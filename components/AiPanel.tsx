"use client";

import { useState } from "react";
import { useMutation, useQueryClient } from "@tanstack/react-query";
import { api } from "@/lib/api";
import type { AiResult, Lead } from "@/lib/types";
import { btnGhost, btnPrimary, cardCls } from "@/lib/constants";

// AI Lead Intelligence: summary, score, probability, next action, follow-up message
export default function AiPanel({ lead }: { lead: Lead }) {
  const qc = useQueryClient();
  const [copied, setCopied] = useState(false);

  const analyze = useMutation({
    mutationFn: () => api<{ result: AiResult }>("/api/ai/analyze", { method: "POST", body: JSON.stringify({ lead_id: lead.id }) }),
    onSuccess: () => {
      qc.invalidateQueries({ queryKey: ["lead", lead.id] });
      qc.invalidateQueries({ queryKey: ["leads"] });
    },
  });

  // Show the fresh result, or the last saved result from the database
  const result = analyze.data?.result ?? lead.ai_result;

  async function copyMessage() {
    if (!result) return;
    await navigator.clipboard.writeText(result.follow_up_message);
    setCopied(true);
    setTimeout(() => setCopied(false), 1500);
  }

  // Bar color changes with the score
  const barColor = (n: number) => (n >= 70 ? "bg-emerald-500" : n >= 40 ? "bg-amber-500" : "bg-rose-500");

  return (
    <section className={`${cardCls} p-4 sm:p-5`}>
      <div className="flex flex-col gap-3 sm:flex-row sm:items-center sm:justify-between">
        <div>
          <h2 className="font-semibold">AI lead intelligence</h2>
          <p className="text-sm text-slate-500">Score, conversion chance and the best next step for this lead.</p>
        </div>
        <button onClick={() => analyze.mutate()} disabled={analyze.isPending} className={btnPrimary}>
          {analyze.isPending ? "Analyzing..." : result ? "Analyze again" : "Analyze with AI"}
        </button>
      </div>

      {analyze.isError && <p className="mt-3 text-sm text-red-600">{analyze.error.message}</p>}

      {!result && !analyze.isPending && (
        <p className="mt-4 rounded-lg bg-slate-50 p-4 text-sm text-slate-500">No analysis yet. Click the button to generate one.</p>
      )}

      {result && (
        <div className="mt-5 space-y-5">
          <div className="grid grid-cols-1 gap-4 sm:grid-cols-2">
            {[
              { label: "Lead score", value: result.score },
              { label: "Conversion probability", value: result.conversion_probability },
            ].map((m) => (
              <div key={m.label} className="rounded-lg bg-slate-50 p-4">
                <div className="flex items-baseline justify-between">
                  <span className="text-sm text-slate-600">{m.label}</span>
                  <span className="text-2xl font-semibold">{m.value}{m.label.startsWith("Conv") ? "%" : "/100"}</span>
                </div>
                <div className="mt-3 h-2 overflow-hidden rounded-full bg-slate-200">
                  <div className={`h-full rounded-full ${barColor(m.value)}`} style={{ width: `${Math.min(100, Math.max(0, m.value))}%` }} />
                </div>
              </div>
            ))}
          </div>

          <div>
            <h3 className="text-sm font-medium text-slate-700">Summary</h3>
            <p className="mt-1 text-sm leading-relaxed text-slate-600">{result.summary}</p>
          </div>
          <div>
            <h3 className="text-sm font-medium text-slate-700">Next best action</h3>
            <p className="mt-1 text-sm leading-relaxed text-slate-600">{result.next_best_action}</p>
          </div>
          <div>
            <div className="flex items-center justify-between">
              <h3 className="text-sm font-medium text-slate-700">Follow-up message</h3>
              <button onClick={copyMessage} className={btnGhost}>{copied ? "Copied" : "Copy"}</button>
            </div>
            <p className="mt-2 whitespace-pre-line rounded-lg border border-slate-200 bg-white p-3 text-sm leading-relaxed text-slate-700">
              {result.follow_up_message}
            </p>
          </div>
          <p className="text-xs text-slate-400">
            {result.source === "gemini" ? "Generated by Google Gemini." : "Demo response (mock AI). Add a Gemini API key to use the real model."}
          </p>
        </div>
      )}
    </section>
  );
}
